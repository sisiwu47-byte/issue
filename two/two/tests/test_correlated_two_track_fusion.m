%% ========================================================================
% TEST 16
% Local scalar KF + correlated fusion
% ========================================================================

function test_local_kf_plus_correlated_fusion(testCase)

pDefault = estimator_default_params();

pFuse = make_zero_process_params();

pFuse.QW = pDefault.QW;
pFuse.QI = pDefault.QI;


%% Explicit numerical guard for local scalar KF

pLocal = struct( ...
    'denomEps', 1e-12);


%% ------------------------------------------------------------------------
% WSS local KF
% -------------------------------------------------------------------------

xWPrev = 0.5;
PWPrev = 0.2;

Rw = 0.4;

zW = 1.8;

[xWPlus, PWPlus, ~, ~, KW] = ...
    local_scalar_kf_step( ...
        xWPrev, ...
        PWPrev, ...
        zW, ...
        Rw, ...
        pDefault.QW, ...
        true, ...
        pLocal);


%% ------------------------------------------------------------------------
% IMU local KF
% -------------------------------------------------------------------------

xIPrev = -0.2;
PIPrev = 0.3;

RI = 0.6;

zI = 1.1;

[xIPlus, PIPlus, ~, ~, KI] = ...
    local_scalar_kf_step( ...
        xIPrev, ...
        PIPrev, ...
        zI, ...
        RI, ...
        pDefault.QI, ...
        true, ...
        pLocal);


%% ------------------------------------------------------------------------
% Correlated two-track fusion
% -------------------------------------------------------------------------

[vxFused, Pfused, alphaW, alphaI, ...
    PWI_minus, PWI_plus, Phi, ...
    condPhi, fusionValid] = ...
    correlated_two_track_fusion( ...
        xWPlus, ...
        PWPlus, ...
        KW, ...
        xIPlus, ...
        PIPlus, ...
        KI, ...
        pDefault.PWI0, ...
        true, ...
        true, ...
        pFuse);


%% ------------------------------------------------------------------------
% Expected PWI prediction/update
% -------------------------------------------------------------------------

expectedPwiMinus = ...
    pDefault.PWI0 + ...
    (pFuse.QW + pFuse.QI) / 2;

expectedPwiPlus = ...
    (1 - KW) * ...
    expectedPwiMinus * ...
    (1 - KI);


%% ------------------------------------------------------------------------
% Expected correlated weights
% -------------------------------------------------------------------------

expectedDen = ...
    PWPlus + ...
    PIPlus - ...
    2 * expectedPwiPlus;

expectedAlphaW = ...
    (PIPlus - expectedPwiPlus) / ...
    expectedDen;

expectedAlphaI = ...
    (PWPlus - expectedPwiPlus) / ...
    expectedDen;


%% Explicit normalization used by fusion implementation

weightSum = ...
    expectedAlphaW + ...
    expectedAlphaI;

expectedAlphaW = ...
    expectedAlphaW / weightSum;

expectedAlphaI = ...
    expectedAlphaI / weightSum;


%% Expected fused state

expectedVxFused = ...
    expectedAlphaW * xWPlus + ...
    expectedAlphaI * xIPlus;


%% ------------------------------------------------------------------------
% Verify composition
% -------------------------------------------------------------------------

testCase.verifyTrue( ...
    fusionValid, ...
    'TEST16: composed local-KF/fusion path should be valid.');


%% State result

testCase.verifyEqual( ...
    vxFused, ...
    expectedVxFused, ...
    'AbsTol', 1e-12, ...
    'TEST16: composed fused velocity mismatch.');


%% PWI prediction

testCase.verifyEqual( ...
    PWI_minus, ...
    expectedPwiMinus, ...
    'AbsTol', 1e-12, ...
    'TEST16: composed PWI_minus mismatch.');


%% PWI posterior

testCase.verifyEqual( ...
    PWI_plus, ...
    expectedPwiPlus, ...
    'AbsTol', 1e-12, ...
    'TEST16: composed PWI_plus mismatch.');


%% Fusion weight sum

testCase.verifyEqual( ...
    alphaW + alphaI, ...
    1, ...
    'AbsTol', 1e-12);


%% Individual fusion weights

testCase.verifyEqual( ...
    alphaW, ...
    expectedAlphaW, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    alphaI, ...
    expectedAlphaI, ...
    'AbsTol', 1e-12);


%% All core outputs finite

testCase.verifyTrue( ...
    isfinite(vxFused));

testCase.verifyTrue( ...
    isfinite(Pfused) && Pfused >= 0);

testCase.verifyTrue( ...
    isfinite(xWPlus) && isfinite(xIPlus));

testCase.verifyTrue( ...
    all(isfinite(Phi(:))));

testCase.verifyTrue( ...
    isfinite(condPhi));

end


