    (1 - KW) * PWI_prev + ...
    (1 - KI);

testCase.verifyGreaterThanOrEqual( ...
    abs(PWI_plus - wrongAdditive), ...
    1e-3, ...
    'TEST2: PWI update incorrectly matches additive form.');

