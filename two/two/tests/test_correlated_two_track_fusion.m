    PWI_prev * (1 - KI);

testCase.verifyGreaterThanOrEqual( ...
    abs(PWI_plus - wrongImuOnly), ...
    1e-3, ...
    'TEST2: PWI update incorrectly matches IMU-only form.');


%% Must not use additive mistaken expression

