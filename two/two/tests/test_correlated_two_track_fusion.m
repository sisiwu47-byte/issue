%% ========================================================================
% TEST 6
% Correlated fusion numerical formula
% ========================================================================

function test_correlated_fusion_numeric(testCase)

pZero = make_zero_process_params();

PW = 4.0;
PI = 9.0;

PWI_prev = 1.5;

xW = 10.0;
xI = 2.0;

[vxFused, Pfused, alphaW, alphaI, ...
    PWI_minus, PWI_plus, Phi, condPhi, fusionValid] = ...
    correlated_two_track_fusion( ...
        xW, PW, 0, ...
        xI, PI, 0, ...
        PWI_prev, ...
        true, true, ...
        pZero);


%% Expected correlated weights

expectedDen = ...
    PW + PI - ...
    2 * PWI_prev;

expectedAlphaW = ...
    (PI - PWI_prev) / expectedDen;

expectedAlphaI = ...
    (PW - PWI_prev) / expectedDen;

expectedVxFused = ...
    expectedAlphaW * xW + ...
    expectedAlphaI * xI;

expectedPfused = ...
    expectedAlphaW^2 * PW + ...
    2 * expectedAlphaW * expectedAlphaI * PWI_prev + ...
    expectedAlphaI^2 * PI;


%% Fusion validity

testCase.verifyTrue( ...
    fusionValid, ...
    'TEST6: normal correlated fusion should be valid.');


%% PWI

testCase.verifyEqual( ...
    PWI_minus, ...
    PWI_prev, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    PWI_plus, ...
    PWI_prev, ...
    'AbsTol', 1e-12);


%% Weight sum

testCase.verifyEqual( ...
    alphaW + alphaI, ...
    1, ...
    'AbsTol', 1e-12, ...
    'TEST6: fusion weights must sum to one.');


%% Individual weights

testCase.verifyEqual( ...
    alphaW, ...
    expectedAlphaW, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    alphaI, ...
    expectedAlphaI, ...
    'AbsTol', 1e-12);


%% Fused estimate

testCase.verifyEqual( ...
    vxFused, ...
    expectedVxFused, ...
    'AbsTol', 1e-12);


%% Fused covariance

testCase.verifyEqual( ...
    Pfused, ...
    expectedPfused, ...
    'AbsTol', 1e-12);


%% Matrix/conditioning safety

testCase.verifyTrue( ...
    all(isfinite(Phi(:))), ...
    'TEST6: Phi must remain finite.');

testCase.verifyTrue( ...
    isfinite(condPhi), ...
    'TEST6: condPhi must remain finite.');

end


%% ========================================================================
% TEST 7
% Correlated fusion differs from independent fusion
% ========================================================================

function test_correlated_differs_from_independent(testCase)

pZero = make_zero_process_params();

PW = 4.0;
PI = 9.0;

PWI_prev = 2.2;

xW = 12.0;
xI = -3.0;


%% Correlated fusion

[vxCorr, PfusedCorr, alphaWCorr, alphaICorr, ...
    ~, PWI_plus, Phi, ~, fusionValid] = ...
    correlated_two_track_fusion( ...
        xW, PW, 0, ...
        xI, PI, 0, ...
        PWI_prev, ...
        true, true, ...
        pZero);


%% Independent inverse-variance fusion

alphaWInd = ...
    (1 / PW) / ...
    (1 / PW + 1 / PI);

alphaIInd = ...
    (1 / PI) / ...
    (1 / PW + 1 / PI);

vxInd = ...
    alphaWInd * xW + ...
    alphaIInd * xI;

PfusedInd = ...
    alphaWInd^2 * PW + ...
    alphaIInd^2 * PI;


%% Expected correlated solution

expectedDen = ...
    PW + PI - ...
    2 * PWI_prev;

expectedAlphaW = ...
    (PI - PWI_prev) / expectedDen;

expectedAlphaI = ...
    (PW - PWI_prev) / expectedDen;

expectedVx = ...
    expectedAlphaW * xW + ...
    expectedAlphaI * xI;

expectedPfused = ...
    expectedAlphaW^2 * PW + ...
    2 * expectedAlphaW * expectedAlphaI * PWI_prev + ...
    expectedAlphaI^2 * PI;


%% Verify correlated result

testCase.verifyTrue(fusionValid);

testCase.verifyEqual( ...
    alphaWCorr, expectedAlphaW, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    alphaICorr, expectedAlphaI, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    vxCorr, expectedVx, ...
    'AbsTol', 1e-12);

testCase.verifyEqual( ...
    PfusedCorr, expectedPfused, ...
    'AbsTol', 1e-12);


%% Must differ from independent fusion

testCase.verifyGreaterThanOrEqual( ...
    abs(vxCorr - vxInd), ...
    1e-3, ...
    ['TEST7: correlated fusion should differ ', ...
     'from independent fusion.']);

testCase.verifyGreaterThanOrEqual( ...
    abs(PfusedCorr - PfusedInd), ...
    1e-3);

testCase.verifyGreaterThanOrEqual( ...
    abs(alphaWCorr - alphaWInd), ...
    1e-3);


%% Numerical checks

testCase.verifyTrue(isfinite(PWI_plus));

testCase.verifyTrue(all(isfinite(Phi(:))));

end


