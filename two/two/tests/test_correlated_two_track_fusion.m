% ========================================================================

function test_pwi_two_sided_update(testCase)

pZero = make_zero_process_params();

PWI_prev = 2.4;

PW = 1.5;
PI = 1.8;

KW = 0.25;
KI = 0.40;

[~, ~, ~, ~, ~, PWI_plus] = ...
    correlated_two_track_fusion( ...
        0, PW, KW, ...
        0, PI, KI, ...
        PWI_prev, ...
        true, true, ...
        pZero);

