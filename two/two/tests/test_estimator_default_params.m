    'TEST4: v_low must be positive.');

end


%% ========================================================================
% TEST 5
% ========================================================================

function test_slip_confidence_parameters(testCase)
% TEST 5:
% Validate slip-confidence thresholds and covariance bounds.

p = estimator_default_params();


%% Slip thresholds

testCase.verifyGreaterThanOrEqual( ...
    p.e_low, ...
    0, ...
    'TEST5: e_low must be non-negative.');

testCase.verifyGreaterThan( ...
    p.e_high, ...
    p.e_low, ...
    'TEST5: e_high must be greater than e_low.');


%% Hard confidence threshold

testCase.verifyGreaterThanOrEqual( ...
    p.rho_hard, ...
    0, ...
    'TEST5: rho_hard must be >= 0.');

testCase.verifyLessThanOrEqual( ...
    p.rho_hard, ...
    1, ...
    'TEST5: rho_hard must be <= 1.');


%% Nominal measurement covariance

testCase.verifyGreaterThan( ...
    p.R0, ...
    0, ...
    'TEST5: R0 must be positive.');


%% Covariance clipping bounds

testCase.verifyGreaterThan( ...
    p.R_min, ...
    0, ...
    'TEST5: R_min must be positive.');

testCase.verifyGreaterThanOrEqual( ...
    p.R_max, ...
    p.R_min, ...
    'TEST5: R_max must be >= R_min.');

end


