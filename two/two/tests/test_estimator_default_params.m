    0.15, ...
    'AbsTol', 1e-12, ...
    'TEST2: eAbs_low should be fixed at 0.15 m/s.');

testCase.verifyEqual( ...
    p.eAbs_high, ...
    0.50, ...
    'AbsTol', 1e-12, ...
    'TEST2: eAbs_high should be fixed at 0.50 m/s.');

