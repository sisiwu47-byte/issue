%% ========================================================================
% TEST 7
% ========================================================================

function test_imu_only_fallback_parameter(testCase)
% TEST 7:
% Maximum allowed IMU-only duration must be finite and positive.

p = estimator_default_params();


%% Positive

testCase.verifyGreaterThan( ...
    p.TimuOnlyMax, ...
    0, ...
    'TEST7: TimuOnlyMax must be positive.');


%% Finite

testCase.verifyTrue( ...
    isfinite(p.TimuOnlyMax), ...
    'TEST7: TimuOnlyMax must be finite.');


%% Should represent at least one estimator step

testCase.verifyGreaterThanOrEqual( ...
    p.TimuOnlyMax, ...
    p.Ts_est, ...
    ['TEST7: TimuOnlyMax should allow at least ', ...
     'one estimator sample.']);

end
