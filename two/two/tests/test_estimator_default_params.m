function tests = test_estimator_default_params
%TEST_ESTIMATOR_DEFAULT_PARAMS
% Unit tests for Stage 3A default estimator parameters.
%
% Covers:
%   TEST 1 - required parameter fields exist
%   TEST 2 - fixed Stage-3A nominal parameter values
%   TEST 3 - timing consistency
%   TEST 4 - vehicle geometry validity
%   TEST 5 - slip-confidence parameter validity
%   TEST 6 - KF covariance/process-noise validity
%   TEST 7 - IMU-only fallback parameter validity
%
% MATLAB execution state: READY TO RUN
% VALIDATION state: PENDING MATLAB VALIDATION
%
% Run:
%   r = runtests('tests/test_estimator_default_params.m');
%   table(r)

tests = functiontests(localfunctions);

end


%% ========================================================================
% Setup
% ========================================================================

function setupOnce(testCase)
% Allow this test file to run independently.

testDir = fileparts(mfilename('fullpath'));
matlabDir = fullfile(testDir, '..', 'matlab');

testCase.verifyTrue( ...
    isfolder(matlabDir), ...
    'Cannot find ../matlab source directory.');

testCase.applyFixture( ...
    matlab.unittest.fixtures.PathFixture(matlabDir));

end


