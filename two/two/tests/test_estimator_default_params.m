%% ========================================================================
% TEST 3
% ========================================================================

function test_timing_consistency(testCase)
% TEST 3:
% Estimator timing parameters must be positive and internally consistent.

p = estimator_default_params();


%% Positive sampling interval

testCase.verifyGreaterThan( ...
    p.Ts_est, ...
    0, ...
    'TEST3: Ts_est must be positive.');


%% Positive window duration

testCase.verifyGreaterThan( ...
    p.Twindow, ...
    0, ...
    'TEST3: Twindow must be positive.');


%% Positive integer window length

testCase.verifyGreaterThan( ...
    p.Nwindow, ...
    0, ...
    'TEST3: Nwindow must be positive.');

testCase.verifyEqual( ...
    p.Nwindow, ...
    round(p.Nwindow), ...
    'TEST3: Nwindow must be integer-valued.');


%% Twindow / Ts_est consistency

expectedNwindow = ...
    round(p.Twindow / p.Ts_est);

testCase.verifyEqual( ...
    p.Nwindow, ...
    expectedNwindow, ...
    ['TEST3: Nwindow must equal ', ...
     'round(Twindow/Ts_est).']);


%% Explicit duration reconstruction

testCase.verifyEqual( ...
    p.Nwindow * p.Ts_est, ...
    p.Twindow, ...
    'AbsTol', 1e-12, ...
    ['TEST3: Nwindow*Ts_est should ', ...
     'reconstruct Twindow.']);

end


