function [analysis,dataset] = analyze_vy_fixed_fusion_v2_5g2_remaining_calibration(varargin)
%ANALYZE_VY_FIXED_FUSION_V2_5G2_REMAINING_CALIBRATION No-simulation analyzer.
% (report, registryRow) performs in-memory integrity analysis before the
% immutable MAT save. (runId) reads that MAT, emits CSV evidence, and never
% writes the MAT.

root=fileparts(fileparts(mfilename('fullpath')));
registryFile=fullfile(root,'results','vy_fixed_fusion_v2_5f_run_registry.csv');
remediationFile=fullfile(root,'results','vy_fixed_fusion_v2_5g2_C02_presim_remediation_registry.csv');
registry=readtable(registryFile,'TextType','string','VariableNamingRule','preserve','Delimiter',',');
allowed=["FWCAL_C02";"FWCAL_C03";"FWCAL_C04";"FWCAL_C05"];

if nargin==2
    report=varargin{1};reg=varargin{2};runId=string(report.runId);
    assert(any(runId==allowed)&&height(reg)==1&&reg.run_id==runId,'V25G2:Analyzer','Run/registry mismatch.');
    [analysis,dataset]=analyze_vy_fixed_fusion_v2_5g1d_C01R1(report,reg);
    analysis.stage='V2.5-G2';analysis.runId=char(runId);
    analysis.performanceBasedSelectionPerformed=false;analysis.weightSelectionPerformed=false;
    analysis.alpha_D='UNSELECTED';analysis.alpha_K='UNSELECTED';analysis.alpha_F='UNSELECTED';
    vals=cell2mat(struct2cell(analysis.gates));analysis.gateCount=numel(vals);
    analysis.gatesTrue=sum(vals);analysis.eligibleForCalibration=all(vals);analysis.passed=all(vals);
    dataset.run_id=char(runId);dataset.role='CALIBRATION_ONLY';dataset.replaces_run_id='NONE';
    dataset.replacement_generation=0;dataset.preregisteredManeuver=table2struct(reg);
    dataset.formalCalibrationEligibility=analysis.eligibleForCalibration;
    dataset.alphaStatus='UNSELECTED';dataset.P_FW_Generated=false;
    return
elseif nargin~=1
    error('V25G2:Usage','Use (report,registryRow) or one run ID.');
end

runId=upper(string(varargin{1}));
assert(isscalar(runId)&&any(runId==allowed),'V25G2:RunId','Run ID must be FWCAL_C02..C05.');
reg=registry(registry.run_id==runId,:);assert(height(reg)==1,'V25G2:Registry','Run row missing.');
resultFile=formal_result_path(root,reg,remediationFile);
if runId=="FWCAL_C02"
    oldFailure=fullfile(root,strrep(char(reg.result_path_reserved),'/',filesep));
    assert(isfile(oldFailure)&&strcmpi(sha256(oldFailure), ...
        'F78B76F1D63CB465B98401BF033E842A6BC440D88237F625AD11E8FF1D9A484F'), ...
        'V25G2:Evidence','Preserved C02 pre-sim failure evidence changed.');
    assert(~strcmpi(oldFailure,resultFile),'V25G2:Evidence', ...
        'Analyzer must exclude the pre-sim failure MAT from formal calibration.');
end
assert(isfile(resultFile),'V25G2:Evidence','Immutable runtime MAT is missing.');
hashBefore=sha256(resultFile);info=dir(resultFile);
S=load(resultFile,'report','dataset');report=S.report;dataset=S.dataset;analysis=report.analysis;
assert(strcmp(string(report.runId),runId)&&report.simCalled&&report.simCallCount==1&& ...
    report.simulationCompleted&&report.carSimRun&&analysis.passed&& ...
    dataset.formalCalibrationEligibility,'V25G2:Evidence','Runtime evidence is incomplete/ineligible.');

acqFile=fullfile(root,'results',sprintf('vy_fixed_fusion_v2_5g2_%s_acquisition_record.csv',runId));
gateFile=fullfile(root,'results',sprintf('vy_fixed_fusion_v2_5g2_%s_integrity_gates.csv',runId));
write_acquisition(acqFile,report,analysis,reg,resultFile,hashBefore,info);
write_gates(gateFile,report,analysis,reg,resultFile,hashBefore);
hashAfter=sha256(resultFile);infoAfter=dir(resultFile);
assert(strcmpi(hashBefore,hashAfter)&&info.bytes==infoAfter.bytes&&info.datenum==infoAfter.datenum, ...
    'V25G2:Immutability','Runtime MAT changed during analyzer-only evidence generation.');

fprintf(['G2_POST_ANALYSIS|id=%s|gates=%d/%d|N=[%d %d %d %d]|t=[%.17g %.17g]|' ...
    'dt=[%.17g %.17g %.17g]|timeDiff=[%.17g %.17g %.17g]|Ay=%d/%d|' ...
    'Kinputs=[%d %d %d]|feedback=%d|replayD=[%.17g %.17g %.17g]|' ...
    'replayK=[%.17g %.17g %.17g]|replayF=[%.17g %.17g %.17g]|fusion=%.17g|' ...
    'truth=%s|truthN=[%d %d]|evalN=%d|steer=[%.17g %.17g %.17g %.17g]|' ...
    'Vx=[%.17g %.17g %.17g]|hash=%s|bytes=%d|eligible=%d|sim=0\n'], ...
    report.runId,analysis.gatesTrue,analysis.gateCount, ...
    analysis.timestamps.D.sampleCount,analysis.timestamps.K.sampleCount, ...
    analysis.timestamps.F.sampleCount,analysis.timestamps.fusion.sampleCount, ...
    analysis.timestamps.fusion.tStart,analysis.timestamps.fusion.tEnd, ...
    analysis.timestamps.fusion.dtMin,analysis.timestamps.fusion.dtMean,analysis.timestamps.fusion.dtMax, ...
    analysis.timestamps.DvsKMaxDiff,analysis.timestamps.DvsFMaxDiff,analysis.timestamps.DvsFusionMaxDiff, ...
    analysis.D.AyUpdate.count,analysis.D.AyUpdate.expectedCount, ...
    analysis.K.processInputs.AxCount,analysis.K.processInputs.AyCount,analysis.K.processInputs.AVzCount, ...
    analysis.F.feedbackAppliedOneCount,analysis.DReplay.maxStateDiff,analysis.DReplay.maxPDiff, ...
    analysis.DReplay.maxDiagDiff,analysis.KReplay.maxStateDiff,analysis.KReplay.maxPDiff, ...
    analysis.KReplay.maxDiagDiff,analysis.FReplay.maxVyDiff,analysis.FReplay.maxPDiff, ...
    analysis.FReplay.maxDiagDiff,analysis.fusionReplay.maxAbsFusionReplayDiff, ...
    analysis.truth.VyAlignment.mode,analysis.truth.VyAlignment.truthOriginalSampleCount, ...
    analysis.truth.VyAlignment.truthAlignedSampleCount,analysis.evaluation.sampleCount, ...
    analysis.steering.commandMaxAbs,analysis.steering.frequencyHz, ...
    analysis.steering.RLMaxAbsRad,analysis.steering.RRMaxAbsRad, ...
    analysis.truth.VxStats.min,analysis.truth.VxStats.mean,analysis.truth.VxStats.max, ...
    hashAfter,info.bytes,analysis.eligibleForCalibration);
fprintf(['G2_COVARIANCE|id=%s|D_asym=%.17g|D_mineig=%.17g|' ...
    'K_asym=%.17g|K_mineig=%.17g|F_minP=%.17g|F_finite=%d\n'],report.runId, ...
    analysis.D.covariance.maxAsymmetry,analysis.D.covariance.minimumEigenvalue, ...
    analysis.K.covariance.maxAsymmetry,analysis.K.covariance.minimumEigenvalue, ...
    analysis.F.minimumP,analysis.F.PFinite);
fprintf('%s ACQUISITION PASS\n',report.runId);
end

