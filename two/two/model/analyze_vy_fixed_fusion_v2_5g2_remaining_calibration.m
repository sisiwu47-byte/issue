function s=replay_text(x)
if isfield(x,'maxStateDiff'),s="PASS_MAX_DIFF_"+string(x.maxStateDiff)+"_"+string(x.maxPDiff)+"_"+string(x.maxDiagDiff);
elseif isfield(x,'maxVyDiff'),s="PASS_MAX_DIFF_"+string(x.maxVyDiff)+"_"+string(x.maxPDiff)+"_"+string(x.maxDiagDiff);
else,s="UNKNOWN";end
end
function s=empty_as_unset(x),if isempty(x),s="UNSET";else,s=string(x);end,end
function s=bool_text(tf,a,b),if tf,s=string(a);else,s=string(b);end,end
function v=asnum(x),if isnumeric(x),v=double(x);else,v=str2double(string(x));end;assert(isscalar(v));end
function file=formal_result_path(root,reg,remediationFile)
if string(reg.run_id)=="FWCAL_C02"
    rem=readtable(remediationFile,'TextType','string','VariableNamingRule','preserve','Delimiter',',');
    rem=rem(rem.run_id=="FWCAL_C02",:);assert(height(rem)==1,'V25G2:Remediation','C02 remediation row missing.');
    file=fullfile(root,strrep(char(rem.new_formal_runtime_path),'/',filesep));
else
    file=fullfile(root,strrep(char(reg.result_path_reserved),'/',filesep));
end
end
