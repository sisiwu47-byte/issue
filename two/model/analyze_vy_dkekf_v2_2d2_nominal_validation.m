function report=analyze_vy_dkekf_v2_2d2_nominal_validation()
%ANALYZE_VY_DKEKF_V2_2D2_NOMINAL_VALIDATION Offline-only D2 analysis.
root=fileparts(fileparts(mfilename('fullpath')));
f=fullfile(root,'results','vy_dkekf_v2_2d2_nominal_validation.mat');
c2File=fullfile(root,'results','vy_dkekf_v2_2c2_preflight.mat');
g1File=fullfile(root,'results','vy_kkf_v2_1g1_nominal_002.mat');
S=load(f,'report');report=S.report;
assert(report.simulationCompleted&&report.simCalled&&report.carSimRun, ...
    'D2 simulation/CarSim completion evidence is missing.');
r=report.raw;

cmd=v(r.d1_steer_cmd_rad);deg=v(r.d1_steer_to_carsim_deg);
fl=v(r.d1_steer_fl_boundary_deg);fr=v(r.d1_steer_fr_boundary_deg);
rl=v(r.d1_steer_rl_boundary_deg);rr=v(r.d1_steer_rr_boundary_deg);
assert(isequal(numel(cmd),numel(deg),numel(fl),numel(fr),numel(rl),numel(rr)), ...
    'Steering evidence logs are not sample-aligned.');
t=double(r.dkekf_x_log1.time(:));n=numel(t);dt=diff(t);
outputLogsAligned=isequal(t,double(r.dkekf_P_log1.time(:)), ...
    double(r.dkekf_diag_log1.time(:)));
assert(outputLogsAligned,'DK-EKF x/P/diag logs do not share exact timestamps.');
[u,inputAlignment]=input_rows_at_hits(r.dkekf_u_log1.data,r.dkekf_u_log1.time,t,10);
assert(inputAlignment.allHitsResolved&&~inputAlignment.ambiguousDuplicate, ...
    'Runtime input log cannot be resolved exactly at every DK-EKF hit.');
x=sample_rows(r.dkekf_x_log1.data,n,3);
p=covariance_pages(r.dkekf_P_log1.data,n);
d=sample_rows(r.dkekf_diag_log1.data,n,7);

ix=abs(cmd)>1e-10;ratio=deg(ix)./cmd(ix);
a=struct();a.runtime=struct('simulationCompleted',report.simulationCompleted, ...
    'simCalled',report.simCalled,'carSimRun',report.carSimRun, ...
    'progDir',report.carSim.progDir,'dataDir',report.carSim.dataDir, ...
    'solverPath',report.carSim.actualSolverPath, ...
    'gDriveRequest',report.carSim.historicalGDriveRequestPresent);
a.steering=struct('sourceMaxAbs_rad',max(abs(cmd)), ...
    'convertedMaxAbs_deg',max(abs(deg)),'ratioMedian',median(ratio), ...
    'ratioMaxError',max(abs(ratio-180/pi)), ...
    'flMaxAbs_deg',max(abs(fl)),'frMaxAbs_deg',max(abs(fr)), ...
    'rlMaxAbs_deg',max(abs(rl)),'rrMaxAbs_deg',max(abs(rr)), ...
    'flConvertedMaxAbsDiff',max(abs(fl-deg)), ...
    'frConvertedMaxAbsDiff',max(abs(fr-deg)), ...
    'flFrMaxAbsDiff',max(abs(fl-fr)), ...
    'frequency_Hz',fitf(r.d1_steer_cmd_rad.time,cmd));
a.steering.frontCommandApplied=a.steering.flConvertedMaxAbsDiff<1e-12&& ...
    a.steering.frConvertedMaxAbsDiff<1e-12&&a.steering.flFrMaxAbsDiff<1e-12&& ...
    a.steering.flMaxAbs_deg>1e-8&&a.steering.frMaxAbs_deg>1e-8;
a.steering.rearZero=a.steering.rlMaxAbs_deg<1e-12&&a.steering.rrMaxAbs_deg<1e-12;
a.steering.pass=abs(a.steering.sourceMaxAbs_rad-.02)<1e-9&& ...
    abs(a.steering.convertedMaxAbs_deg-.02*180/pi)<1e-9&& ...
    a.steering.ratioMaxError<1e-10&&abs(a.steering.frequency_Hz-.4)<1e-5&& ...
    a.steering.frontCommandApplied&&a.steering.rearZero;

a.timing=struct('xSampleCount',r.dkekf_x_log1.sampleCount, ...
    'pSampleCount',r.dkekf_P_log1.sampleCount, ...
    'diagSampleCount',r.dkekf_diag_log1.sampleCount, ...
    'rawInputSampleCount',r.dkekf_u_log1.sampleCount, ...
    'tStart',t(1),'tEnd',t(end),'dtMin',min(dt),'dtMean',mean(dt), ...
    'dtMax',max(dt),'duplicateTimestampCount',nnz(dt<=0), ...
    'missingHitCount',sum(max(round(dt/.01)-1,0)), ...
    'outputLogsAligned',outputLogsAligned,'inputAlignment',inputAlignment);
a.timing.dkekf100Hz=all(abs(dt-.01)<1e-12)&& ...
    a.timing.duplicateTimestampCount==0&&a.timing.missingHitCount==0&& ...
    n==round((t(end)-t(1))/.01)+1&&abs(t(1))<1e-12&&abs(t(end)-16)<1e-12;

reset=u(:,6)>.5;doAy=u(:,5)>.5;applied=d(:,4)>.5;
a.reset=struct('highCount',nnz(reset),'timestamps',t(reset), ...
    'onceAtT0',nnz(reset)==1&&abs(t(reset))<1e-12, ...
    'initialStatePrior',[u(1,4);0;0],'initialCovariancePrior',diag([.1 .1 .1]), ...
    'runtimeFirstState',x(1,:).','runtimeFirstCovariance',p(:,:,1), ...
    'trueVyInitialization',false);
a.ayScheduler=struct('doAyUpdateCount',nnz(doAy), ...
    'ayUpdateAppliedCount',nnz(applied),'doAyUpdateTimestamps',t(doAy), ...
    'ayUpdateAppliedTimestamps',t(applied), ...
    'sequenceExact',isequal(doAy,applied));
a.ayScheduler.actual20Hz=a.ayScheduler.sequenceExact&&nnz(doAy)==321&& ...
    all(abs(diff(t(doAy))-.05)<1e-12)&&abs(t(find(doAy,1))-0)<1e-12&& ...
    abs(t(find(doAy,1,'last'))-16)<1e-12;

a.dimensions=struct('x',size(x,2),'P',size(p(:,:,1)),'diag',size(d,2));
a.numeric=struct('allXFinite',all(isfinite(x(:))),'allPFinite',all(isfinite(p(:))), ...
    'allDiagFinite',all(isfinite(d(:))));
a.numeric.dimensionsOK=a.dimensions.x==3&&isequal(a.dimensions.P,[3 3])&& ...
    a.dimensions.diag==7;
a.numeric.allFinite=a.numeric.allXFinite&&a.numeric.allPFinite&&a.numeric.allDiagFinite;
pd=zeros(n,3);minEig=inf;maxAsym=0;
for k=1:n
    pk=p(:,:,k);pd(k,:)=diag(pk).';
    maxAsym=max(maxAsym,max(abs(pk-pk.'),[],'all'));
    minEig=min(minEig,min(eig((pk+pk.')/2)));
end
a.covariance=struct('maxAsymmetry',maxAsym,'minimumEigenvalue',minEig, ...
    'P11',cov_stats(pd(:,1)),'P22',cov_stats(pd(:,2)),'P33',cov_stats(pd(:,3)));
a.covariance.valid=maxAsym<=1e-12&&minEig>=-1e-12;

[vxTrue,vxAlign]=truth_at(r.Vx_true_log,t,1);
[vyTrue,vyAlign]=truth_at(r.vy_true_log1,t,1);
[rDeg,rAlign]=truth_at(r.avz_log1,t,1);rTrue=rDeg*pi/180;
a.offlineTruth=struct('Vx',vxAlign,'Vy',vyAlign,'r',rAlign, ...
    'rSourceUnit','deg/s','rAnalysisUnit','rad/s','rConversion','pi/180', ...
    'noExtrapolation',true,'usedOnline',false);
evx=x(:,1)-vxTrue;evy=x(:,2)-vyTrue;er=x(:,3)-rTrue;
a.performance=struct('Vx',error_metrics(evx),'Vy',error_metrics(evy), ...
    'r',error_metrics(er),'VyHatRange',[min(x(:,2)) max(x(:,2))], ...
    'VyTrueRange',[min(vyTrue) max(vyTrue)]);

rMeas=u(:,3);rAbs=abs(rMeas);low=rAbs<=.01;higher=~low;
a.yaw=struct('meanAbs',mean(rAbs),'medianAbs',median(rAbs), ...
    'p95Abs',pct(rAbs,95),'maxAbs',max(rAbs), ...
    'lowCount',nnz(low),'lowFraction',mean(low), ...
    'higherCount',nnz(higher),'higherFraction',mean(higher), ...
    'threshold_radps',.01,'lifeSigGate',false);
a.vyPartitions=struct('lowR',partition_error(evy,low), ...
    'higherR',partition_error(evy,higher));

a.nis=struct('Vx',nis_stats(d(:,1)),'r',nis_stats(d(:,2)), ...
    'Ay',nis_stats(d(applied,3)));
a.nis.Ay.sampleCount=nnz(applied);
a.innovations=struct('Vx',innovation_stats(d(:,5)), ...
    'r',innovation_stats(d(:,6)), ...
    'Ay',innovation_stats(d(applied,7)));
a.innovations.Ay.sampleCount=nnz(applied);

[rx,rp,rd]=replay(u);
a.exactReplay=struct('maxAbsXDiff',max(abs(rx(:)-x(:))), ...
    'maxAbsPDiff',max(abs(rp(:)-p(:))), ...
    'maxAbsDiagDiff',max(abs(rd(:)-d(:))));
a.exactReplay.pass=all([a.exactReplay.maxAbsXDiff a.exactReplay.maxAbsPDiff ...
    a.exactReplay.maxAbsDiagDiff]<=1e-12);
a.oneHitSemantics=struct('pass',a.timing.dkekf100Hz&&a.exactReplay.pass&& ...
    inputAlignment.allHitsResolved&&~inputAlignment.timestampShiftApplied, ...
    'statement','ONE 100-HZ FUNCTION-CALL HIT = ONE COMMITTED DK-EKF STATE ADVANCE');

c2=load(c2File,'report');a.fairness=c2.report.static.fairness;
a.fairness.pass=~a.fairness.trueVyOnline&&a.fairness.trueVxMeasurementOnly&& ...
    a.fairness.axPredictionInput&&a.fairness.avzMeasurementOnly&& ...
    a.fairness.ayMeasurementOnly&&a.fairness.sharedStateAndP&& ...
    ~a.fairness.outputFusion&&~a.fairness.lifeSig&&~a.fairness.adaptiveFusion;
a.hashIntegrity=struct('validationModelUnchanged',report.validationModelHashUnchanged, ...
    'acceptedTargetUnchanged',report.acceptedTargetHashUnchanged, ...
    'allFrozenUnchanged',report.allFrozenHashesUnchanged, ...
    'validationModelHash',report.validationModelHashAfter, ...
    'acceptedTargetHash',report.acceptedTargetHashAfter);

a.gates=struct('runtimeValidity',report.simulationCompleted&&report.simCalled&& ...
    report.carSimRun&&~report.carSim.historicalGDriveRequestPresent&&a.steering.pass&& ...
    a.timing.dkekf100Hz&&a.reset.onceAtT0&&a.ayScheduler.actual20Hz, ...
    'numericalValidity',a.numeric.dimensionsOK&&a.numeric.allFinite&&a.covariance.valid, ...
    'truthMetricsValid',all([isfinite(struct2array(a.performance.Vx)) ...
    isfinite(struct2array(a.performance.Vy)) isfinite(struct2array(a.performance.r))]), ...
    'nisValid',all(isfinite([d(:,1);d(:,2);d(applied,3)])), ...
    'replayValidity',a.exactReplay.pass&&a.oneHitSemantics.pass, ...
    'fairnessValidity',a.fairness.pass,'hashIntegrity', ...
    report.validationModelHashUnchanged&&report.acceptedTargetHashUnchanged&& ...
    report.allFrozenHashesUnchanged);
a.pass=all(struct2array(a.gates));
if a.pass,a.kkfReference=kkf_comparison(g1File,a.performance.Vy,a.steering,report.nominal);else,a.kkfReference=struct('performed',false,'reason','D2 gates invalid');end
report.analysis=a;save(f,'report','-v7.3');
fprintf(['V2_2D2_ANALYSIS|pass=%d|steer=[%.15g %.15g %.15g]|front=[%.15g %.15g]|rear=[%.3g %.3g]|' ...
    'samples=%d|t=[%.15g %.15g]|dt=[%.15g %.15g %.15g]|reset=%d|Ay=%d/%d|' ...
    'P=[%.3g %.15g]|replay=[%.3g %.3g %.3g]|Vx=[%.15g %.15g %.15g %.15g %.15g]|' ...
    'Vy=[%.15g %.15g %.15g %.15g %.15g]|r=[%.15g %.15g %.15g %.15g %.15g]\n'], ...
    a.pass,a.steering.sourceMaxAbs_rad,a.steering.convertedMaxAbs_deg, ...
    a.steering.ratioMedian,a.steering.flMaxAbs_deg,a.steering.frMaxAbs_deg, ...
    a.steering.rlMaxAbs_deg,a.steering.rrMaxAbs_deg,n,t(1),t(end),min(dt),mean(dt),max(dt), ...
    a.reset.highCount,a.ayScheduler.doAyUpdateCount,a.ayScheduler.ayUpdateAppliedCount, ...
    a.covariance.maxAsymmetry,a.covariance.minimumEigenvalue, ...
    a.exactReplay.maxAbsXDiff,a.exactReplay.maxAbsPDiff,a.exactReplay.maxAbsDiagDiff, ...
    metrics_vec(a.performance.Vx),metrics_vec(a.performance.Vy),metrics_vec(a.performance.r));
fprintf('NIS|Vx=[%.15g %.15g %.15g %.15g %.15g]|r=[%.15g %.15g %.15g %.15g %.15g]|AyN=%d|Ay=[%.15g %.15g %.15g %.15g %.15g]\n', ...
    nis_vec(a.nis.Vx),nis_vec(a.nis.r),a.nis.Ay.sampleCount,nis_vec(a.nis.Ay));
fprintf('PDIAG|P11=[%.15g %.15g %.15g %.15g %.15g]|P22=[%.15g %.15g %.15g %.15g %.15g]|P33=[%.15g %.15g %.15g %.15g %.15g]\n', ...
    cov_vec(a.covariance.P11),cov_vec(a.covariance.P22),cov_vec(a.covariance.P33));
fprintf('YAW|mean=%.15g|median=%.15g|p95=%.15g|max=%.15g|low=%d/%.15g|higher=%d/%.15g\n', ...
    a.yaw.meanAbs,a.yaw.medianAbs,a.yaw.p95Abs,a.yaw.maxAbs, ...
    a.yaw.lowCount,a.yaw.lowFraction,a.yaw.higherCount,a.yaw.higherFraction);
end

