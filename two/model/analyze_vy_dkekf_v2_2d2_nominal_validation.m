function a=sample_rows(data,n,w)
a=double(data);s=size(a);
if ismatrix(a)
    if isequal(s,[n w]),return;end
    if isequal(s,[w n]),a=a.';return;end
end
if numel(a)==n*w,a=reshape(a,w,n).';return;end
error('VY_DKEKF:LogShape','Cannot resolve %d-wide log with size %s.',w,mat2str(s));
end
function [hits,audit]=input_rows_at_hits(data,inputTime,hitTime,w)
inputTime=double(inputTime(:));a=sample_rows(data,numel(inputTime),w);
hits=zeros(numel(hitTime),w);matchCount=zeros(numel(hitTime),1);nearCount=zeros(numel(hitTime),1);
nearestDelta=zeros(numel(hitTime),1);tolerance=zeros(numel(hitTime),1);ambiguous=false;
for k=1:numel(hitTime)
    tol=32*eps(max(1,abs(hitTime(k))));tolerance(k)=tol;delta=abs(inputTime-hitTime(k));
    nearestDelta(k)=min(delta);ix=find(delta==nearestDelta(k));
    matchCount(k)=numel(ix);nearCount(k)=nnz(delta<=tol);
    if nearestDelta(k)>tol,continue;end
    c=a(ix,:);if size(c,1)>1&&any(max(abs(c-c(end,:)),[],2)>1e-12),ambiguous=true;end
    hits(k,:)=c(end,:);
end
audit=struct('rawInputSampleCount',numel(inputTime),'hitSampleCount',numel(hitTime), ...
    'matchCountPerHit',matchCount,'nearCoincidentCountPerHit',nearCount, ...
    'nearestTimeDelta',nearestDelta,'timeTolerance',tolerance, ...
    'exactTimestampHitCount',nnz(nearestDelta==0), ...
    'roundoffResolvedHitCount',nnz(nearestDelta>0&nearestDelta<=tolerance), ...
    'maxNearestTimeDelta',max(nearestDelta), ...
    'allHitsResolved',all(matchCount>=1)&&all(nearestDelta<=tolerance), ...
    'duplicateMatchCount',nnz(matchCount>1),'ambiguousDuplicate',ambiguous, ...
    'timestampShiftApplied',false,'machineRoundoffToleranceOnly',all(nearestDelta<=tolerance));
end
function p=covariance_pages(data,n)
p=double(data);s=size(p);
if ndims(p)==3&&isequal(s,[3 3 n]),return;end
if ndims(p)==3&&isequal(s,[n 3 3]),p=permute(p,[2 3 1]);return;end
if ismatrix(p)&&isequal(s,[n 9]),p=reshape(p.',3,3,n);return;end
if numel(p)==9*n,p=reshape(p,3,3,n);return;end
error('VY_DKEKF:LogShape','Cannot resolve covariance log size %s.',mat2str(s));
end
function [y,a]=truth_at(rec,t,w)
tr=double(rec.time(:));yr=sample_rows(rec.data,numel(tr),w);[tr,ia]=unique(tr,'stable');yr=yr(ia,:);
tol=64*eps(max(1,max(abs(t))));assert(t(1)>=tr(1)-tol&&t(end)<=tr(end)+tol, ...
    'Truth coverage does not contain every estimator timestamp; extrapolation forbidden.');
[tf,loc]=ismember(t,tr);
if all(tf),y=yr(loc,:);method='exact timestamp match';maxDelta=0;
else,y=interp1(tr,yr,t,'linear');assert(all(isfinite(y(:))),'Truth interpolation failed.');method='linear interpolation, no extrapolation';maxDelta=max(arrayfun(@(q)min(abs(tr-q)),t));end
a=struct('sourceSampleCount',numel(tr),'targetSampleCount',numel(t), ...
    'sourceStart',tr(1),'sourceEnd',tr(end),'method',method,'maxNearestTimeDelta',maxDelta);
end
function s=error_metrics(e)
s=struct('RMSE',sqrt(mean(e.^2)),'MAE',mean(abs(e)),'Bias',mean(e), ...
    'MaxAbsError',max(abs(e)),'FinalError',e(end));
end
function s=partition_error(e,m)
assert(any(m),'Empty diagnostic partition.');s=error_metrics(e(m));s.sampleCount=nnz(m);
end
function s=nis_stats(z)
assert(~isempty(z)&&all(isfinite(z)));s=struct('mean',mean(z),'median',median(z), ...
    'p95',pct(z,95),'max',max(z),'fractionLE_3_8414588',mean(z<=3.8414588));
end
function s=innovation_stats(z)
assert(~isempty(z)&&all(isfinite(z)));s=struct('mean',mean(z), ...
    'RMS',sqrt(mean(z.^2)),'maxAbs',max(abs(z)));
end
function s=cov_stats(z)
s=struct('initial',z(1),'final',z(end),'min',min(z),'max',max(z),'mean',mean(z));
end
function q=pct(z,p)
z=sort(z(:));x=1+(numel(z)-1)*p/100;i=floor(x);j=ceil(x);
if i==j,q=z(i);else,q=z(i)+(x-i)*(z(j)-z(i));end
end
function f=fitf(t,y),f=fminbnd(@(q)fiterr(q,t,y),.1,1);end
function e=fiterr(f,t,y),A=[sin(2*pi*f*t(:)) cos(2*pi*f*t(:))];e=norm(A*(A\y(:))-y(:))^2;end
function [xr,pr,dr]=replay(u)
n=size(u,1);xr=zeros(n,3);pr=zeros(3,3,n);dr=zeros(n,7);
par=struct('m',1860,'Iz',2687.1,'a',1.18,'b',1.77,'track',1.575,'Rw',.393, ...
    'k_f',.78181,'k_r',1.09186);
cfg=struct('Q_DK',diag([1e-4 1e-4 1e-4]),'R_Vx',1e-4, ...
    'R_r',3.365172961808e-4,'R_Ay',1e-2,'jacobianStep',1e-6, ...
    'denomEps',1e-12,'lambda',zeros(4,1));
P0=diag([.1 .1 .1]);init=false;xs=zeros(3,1);ps=P0;
for k=1:n
    if ~init||u(k,6)>.5,x0=[u(k,4);0;0];p0=P0;else,x0=xs;p0=ps;end
    [xn,pn,info]=vy_dkekf_baseline_step(x0,p0,u(k,1),u(k,7:10).', ...
        u(k,4),u(k,3),u(k,2),u(k,5),.01,par,cfg);
    na=info.Ay.NIS;if ~info.Ay.updateApplied&&isnan(na),na=0;end
    xr(k,:)=xn.';pr(:,:,k)=pn;
    dr(k,:)=[info.Vx.NIS info.r.NIS na double(info.Ay.updateApplied) ...
        info.Vx.innovation info.r.innovation info.Ay.innovation];
    xs=xn;ps=pn;init=true;
end
end
function c=kkf_comparison(f,dk,steer,nominal)
S=load(f,'report');k=S.report;assert(isfield(k,'analysis'),'G1-A analyzed evidence missing.');
km=k.analysis.performance.Vy;cond=k.condition;
c=struct('performed',true,'sourceFile',f,'kkf',km,'dkekf',dk, ...
    'differenceDKminusK',struct('RMSE',dk.RMSE-km.RMSE,'MAE',dk.MAE-km.MAE, ...
    'Bias',dk.Bias-km.Bias,'MaxAbsError',dk.MaxAbsError-km.MaxAbsError, ...
    'FinalError',dk.FinalError-km.FinalError));
c.sameCommandedCondition=cond.Vx_mps==nominal.Vx_mps&& ...
    cond.steerAmplitude_rad==nominal.steerAmplitude_rad&& ...
    cond.steerFrequency_Hz==nominal.steerFrequency_Hz&&k.stopTime_s==16;
c.genuineSteeringBoth=k.steeringGate.pass&&steer.pass;
c.applesToApples=c.sameCommandedCondition&&c.genuineSteeringBoth;
end
function x=metrics_vec(s),x=[s.RMSE s.MAE s.Bias s.MaxAbsError s.FinalError];end
function x=nis_vec(s),x=[s.mean s.median s.p95 s.max s.fractionLE_3_8414588];end
function x=cov_vec(s),x=[s.initial s.final s.min s.max s.mean];end
