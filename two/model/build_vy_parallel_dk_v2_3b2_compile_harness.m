function build = build_vy_parallel_dk_v2_3b2_compile_harness()
%BUILD_VY_PARALLEL_DK_V2_3B2_COMPILE_HARNESS Exact-copy estimator harness.
% Copies only the actual D/K estimator structures and their scheduler/reset
% boundaries from the formal parallel target. It does not compile or run.

root = fileparts(fileparts(mfilename('fullpath')));
md = fullfile(root,'model');
sourceFile = fullfile(md,'vx_vy_parallel_dk_v2_3.slx');
harnessFile = fullfile(md,'vx_vy_parallel_dk_v2_3b2_compile_harness.slx');
sourceExpected = '98461db290723a5ccdf62398ce5063de0c9b6c7586334d479b159a771eb128c0';
[frozenFiles,expectedHashes] = frozen_manifest(root);
before = snapshot(frozenFiles);
assert(strcmp(file_sha256(sourceFile),sourceExpected), ...
    'Formal parallel target hash mismatch before harness build.');
assert(records_match(before,expectedHashes), ...
    'A frozen object hash differs before harness build.');

addpath(md);
Simulink.fileGenControl('set', ...
    'CacheFolder',fullfile(tempdir,'vy_parallel_dk_v2_3b2_cache'), ...
    'CodeGenFolder',fullfile(tempdir,'vy_parallel_dk_v2_3b2_codegen'), ...
    'createDir',true);
load_system('simulink');
load_system(sourceFile);
source = 'vx_vy_parallel_dk_v2_3';
h = 'vx_vy_parallel_dk_v2_3b2_compile_harness';
if bdIsLoaded(h), close_system(h,0); end
new_system(h);
cleanup = onCleanup(@()close_models(source,h));
set_param(h,'SolverType','Fixed-step','Solver','FixedStepDiscrete', ...
    'FixedStep','0.001','StartTime','0','StopTime','0.1');

% Copy the exact estimator structures and their established boundary blocks.
copies = { ...
    'Parallel D-EKF 100Hz',          [760 120 990 270]; ...
    'Parallel D-EKF 100Hz Scheduler',[500 45 675 80]; ...
    'Parallel D-EKF Input RT 100Hz', [530 210 700 245]; ...
    'Parallel D Control Mux',        [390 150 395 220]; ...
    'Parallel D Measurement Mux',    [390 280 395 340]; ...
    'Parallel D Input Mux',          [455 160 460 330]; ...
    'Parallel D Output Demux',       [1060 120 1065 270]; ...
    'Parallel D Full P Extract',     [1060 315 1065 415]; ...
    'Parallel D P 2x2',              [1170 350 1280 385]; ...
    'K-KF 100Hz',                    [760 540 990 700]; ...
    'K-KF 100Hz Scheduler',          [500 470 675 505]; ...
    'K-KF IMU Mux',                  [500 555 505 640]; ...
    'K-KF Vx RT 100Hz',              [520 670 690 705]; ...
    'K-KF Reset First Call',         [530 740 610 770]};
for k=1:size(copies,1)
    add_block([source '/' copies{k,1}],[h '/' copies{k,1}], ...
        'Position',copies{k,2});
end

% Preserve the frozen D-EKF A20 model-workspace configuration.
ws = get_param(h,'ModelWorkspace');
assignin(ws,'vy_v17_mode_code',20);

% Deterministic physical compile sources; these are not vehicle models and
% are never used for performance validation.
ax = add_const(h,'Harness Ax IMU',0.1,0.01,[70 530 180 560]);
ay = add_const(h,'Harness Ay IMU',0.2,0.01,[70 585 180 615]);
avz = add_const(h,'Harness AVz IMU',0.01,0.01,[70 640 180 670]);
vx = add_const(h,'Harness True Vx',20,0.001,[70 175 180 205]);
steer = add_const(h,'Harness Steering Rad','[0.01;0.01;0;0]',0.01, ...
    [70 230 180 260]);

dSub=[h '/Parallel D-EKF 100Hz'];dSched=[h '/Parallel D-EKF 100Hz Scheduler'];
dRt=[h '/Parallel D-EKF Input RT 100Hz'];dControl=[h '/Parallel D Control Mux'];
dMeas=[h '/Parallel D Measurement Mux'];dInput=[h '/Parallel D Input Mux'];
dDemux=[h '/Parallel D Output Demux'];dPExtract=[h '/Parallel D Full P Extract'];
dP=[h '/Parallel D P 2x2'];
kSub=[h '/K-KF 100Hz'];kSched=[h '/K-KF 100Hz Scheduler'];
kImu=[h '/K-KF IMU Mux'];kVxRt=[h '/K-KF Vx RT 100Hz'];
kReset=[h '/K-KF Reset First Call'];

connect(h,vx,1,dControl,1);connect(h,steer,1,dControl,2);
connect(h,ay,1,dMeas,1);connect(h,avz,1,dMeas,2);
connect(h,dControl,1,dInput,1);connect(h,dMeas,1,dInput,2);
connect(h,dInput,1,dRt,1);connect(h,dRt,1,dSub,1);
connect_trigger(h,dSched,dSub);
connect(h,dSub,1,dDemux,1);connect(h,dSub,1,dPExtract,1);
connect(h,dPExtract,2,dP,1);

connect(h,ax,1,kImu,1);connect(h,ay,1,kImu,2);connect(h,avz,1,kImu,3);
connect(h,kImu,1,kSub,1);connect(h,vx,1,kVxRt,1);
connect(h,kVxRt,1,kSub,2);connect(h,kReset,1,kSub,3);
connect_trigger(h,kSched,kSub);

% Observation-only outputs. No D/K output is fed into an estimator input.
dXLog=add_ws(h,dDemux,1,'harness_dekf_x_log',[1370 120 1530 150]);
dPLog=add_ws(h,dP,1,'harness_dekf_P_log',[1370 350 1530 380]);
dDiagLog=add_ws(h,dDemux,3,'harness_dekf_diag_log',[1370 235 1530 265]);
kXLog=add_ws(h,kSub,1,'harness_kkf_x_log',[1080 550 1240 580]);
kPLog=add_ws(h,kSub,2,'harness_kkf_P_log',[1080 610 1240 640]);
kDiagLog=add_ws(h,kSub,3,'harness_kkf_diag_log',[1080 670 1240 700]);

% Unused observation slices terminate locally.
add_term(h,dDemux,2,'Harness D Pdiag Term',[1160 185 1180 205]);
add_term(h,dPExtract,1,'Harness D P Head Term',[1160 310 1180 330]);
add_term(h,dPExtract,3,'Harness D P Tail Term',[1160 410 1180 430]);

% Expose frozen A20 useAy diagnostic y(60) as a compiled scalar. This is an
% observation branch only; the actual gate remains internal to the wrapper.
dAyExtract=[h '/Harness D Ay Gate Extract'];
add_block('simulink/Signal Routing/Demux',dAyExtract,'Outputs','[59 1 9]', ...
    'Position',[1060 455 1065 545]);
connect(h,dSub,1,dAyExtract,1);
add_term(h,dAyExtract,1,'Harness D Ay Gate Head Term',[1160 455 1180 475]);
dAyGateLog=add_ws(h,dAyExtract,2,'harness_dekf_ay_gate_log',[1210 490 1380 520]);
add_term(h,dAyExtract,3,'Harness D Ay Gate Tail Term',[1160 530 1180 550]);

commonMux=[h '/Harness Physical Input Log Mux'];
commonLog=[h '/harness_parallel_input_log'];
add_block('simulink/Signal Routing/Mux',commonMux,'Inputs','[1 1 1 1 4 1]', ...
    'Position',[280 805 285 940]);
add_block('simulink/Sinks/To Workspace',commonLog, ...
    'VariableName','harness_parallel_input_log','SaveFormat','Timeseries', ...
    'Position',[370 855 560 885]);
connect(h,ax,1,commonMux,1);connect(h,ay,1,commonMux,2);
connect(h,avz,1,commonMux,3);connect(h,vx,1,commonMux,4);
connect(h,steer,1,commonMux,5);connect(h,kReset,1,commonMux,6);
connect(h,commonMux,1,commonLog,1);

% Static copy identity checks before saving.
dFcn=find_system(dSub,'LookUnderMasks','all','FollowLinks','on', ...
    'BlockType','MATLABFcn');
assert(numel(dFcn)==1 && strcmp(regexprep(get_param(dFcn{1},'MATLABFcn'),'\s+',''), ...
    'vy_dynamic_ekf_v1_17(u,vy_v17_mode_code)'), ...
    'Harness D wrapper differs from parallel target.');
assert(strcmp(wrapper_chart_script([kSub '/K-KF Wrapper']), ...
    wrapper_chart_script([source '/K-KF 100Hz/K-KF Wrapper'])), ...
    'Harness K wrapper chart differs from parallel target.');
assert(isempty(find_system(h,'LookUnderMasks','all','FollowLinks','on', ...
    'BlockType','S-Function','FunctionName','vs_sf')), ...
    'Harness unexpectedly contains the CarSim vs_sf boundary.');

save_system(h,harnessFile);
close_system(h,0);close_system(source,0);clear cleanup
after=snapshot(frozenFiles);
assert(records_equal(before,after)&&records_match(after,expectedHashes), ...
    'Frozen object changed during harness build.');
assert(strcmp(file_sha256(sourceFile),sourceExpected), ...
    'Formal parallel target changed during harness build.');

build=struct('stage','V2.3-B2','sourceFile',sourceFile, ...
    'sourceHash',sourceExpected,'harnessFile',harnessFile,'modelName',h, ...
    'harnessHash',file_sha256(harnessFile),'frozenBefore',before, ...
    'frozenAfter',after,'dSubsystem',dSub,'dScheduler',dSched, ...
    'dInputRateTransition',dRt,'dControlMux',dControl, ...
    'dMeasurementMux',dMeas,'dInputMux',dInput,'dOutputDemux',dDemux, ...
    'dPExtract',dPExtract,'dP',dP,'dAyExtract',dAyExtract, ...
    'dAyGateLog',dAyGateLog,'kSubsystem',kSub,'kScheduler',kSched, ...
    'kImuMux',kImu,'kVxRateTransition',kVxRt,'kReset',kReset, ...
    'axSource',ax,'aySource',ay,'avzSource',avz,'vxSource',vx, ...
    'steeringSource',steer,'dLogs',{{dXLog,dPLog,dDiagLog}}, ...
    'kLogs',{{kXLog,kPLog,kDiagLog}},'commonLog',commonLog, ...
    'copyMethod','direct add_block copy from formal parallel target', ...
    'dResetSemantics','internal empty-persistent/mode-change lifecycle', ...
    'kResetSemantics','independent copied first-hit Step', ...
    'simCalled',false,'carSimRun',false);
fprintf('V2_3B2_BUILD_OK|hash=%s|vs_sf=0|sim=0|carsim=0\n',build.harnessHash);
end

function p=add_const(m,name,value,sampleTime,pos)
p=[m '/' name];
if isnumeric(value), value=mat2str(value); end
add_block('simulink/Sources/Constant',p,'Value',value, ...
    'SampleTime',num2str(sampleTime,17),'OutDataTypeStr','double','Position',pos);
end
function connect(m,s,o,d,i)
sp=get_param(s,'PortHandles');dp=get_param(d,'PortHandles');
add_line(m,sp.Outport(o),dp.Inport(i),'autorouting','on');
end
function connect_trigger(m,s,d)
sp=get_param(s,'PortHandles');dp=get_param(d,'PortHandles');
add_line(m,sp.Outport(1),dp.Trigger(1),'autorouting','on');
end
function p=add_ws(m,s,o,name,pos)
p=[m '/' name];add_block('simulink/Sinks/To Workspace',p, ...
    'VariableName',name,'SaveFormat','Timeseries','Position',pos);
connect(m,s,o,p,1);
end
function p=add_term(m,s,o,name,pos)
p=[m '/' name];add_block('simulink/Sinks/Terminator',p,'Position',pos);
connect(m,s,o,p,1);
end
