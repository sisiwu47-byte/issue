function y = vy_dynamic_ekf(w)
% VY_DYNAMIC_EKF
% Simulink wrapper for vy_dynamic_ekf_step
%
% Simulink输入：
%   w : 7x1
%
%   w(1) = vx_hat
%   w(2) = Steer_FL
%   w(3) = Steer_FR
%   w(4) = Steer_RL
%   w(5) = Steer_RR
%   w(6) = Ay_IMU
%   w(7) = AVz_IMU
%
% Simulink输出：
%   y : 13x1
%
%   y(1:2)   = [Vy_hat; r_hat]
%   y(3:4)   = [P11; P22]
%   y(5:13)  = [NIS;
%                Fy_FL; Fy_FR; Fy_RL; Fy_RR;
%                alpha_FL; alpha_FR; alpha_RL; alpha_RR]

persistent x P


%% =========================================================
% 1. EKF内部状态初始化
% ==========================================================

if isempty(x)

    x = [0;0];

end


if isempty(P)

    P = eye(2)*0.1;

end


%% =========================================================
% 2. Simulink单输入向量拆分
% ==========================================================

w = w(:);

u = w(1:5);

z = w(6:7);


%% =========================================================
% 3. 固定车辆参数
% ==========================================================

par.m = 1860;

par.Iz = 2687.1;

par.a = 1.18;

par.b = 1.77;

par.track = 1.575;

par.Rw = 0.393;


%% =========================================================
% 4. EKF参数
% ==========================================================

cfg.dt = 0.01;

cfg.Q = diag([1e-4,1e-3]);

cfg.R = diag([1e-2,1e-2]);

cfg.denomEps = 1e-12;

cfg.lambda = zeros(4,1);


%% =========================================================
% 5. EKF一步预测 + 更新
% ==========================================================

[x_new,P_new,info] = ...
    vy_dynamic_ekf_step( ...
    x, ...
    P, ...
    u, ...
    z, ...
    par, ...
    cfg);


%% =========================================================
% 6. 保存到下一采样时刻
% ==========================================================

x = x_new;

P = P_new;


%% =========================================================
% 7. 整理成固定13维Simulink输出
% ==========================================================

y = zeros(13,1);


% ---------- 估计状态 ----------

y(1) = x_new(1);        % Vy_hat

y(2) = x_new(2);        % r_hat


% ---------- 协方差 ----------

y(3) = P_new(1,1);      % P_Vy

y(4) = P_new(2,2);      % P_r


% ---------- EKF诊断 ----------

y(5) = info.NIS;


% ---------- 四轮横向力 ----------

y(6) = info.Fy_FL;

y(7) = info.Fy_FR;

y(8) = info.Fy_RL;

y(9) = info.Fy_RR;


% ---------- 四轮侧偏角 ----------

y(10) = info.alpha_FL;

y(11) = info.alpha_FR;

y(12) = info.alpha_RL;

y(13) = info.alpha_RR;


end