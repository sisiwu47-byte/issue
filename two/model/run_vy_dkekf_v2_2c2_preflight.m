function r=hash_files(files)
r=repmat(struct('path','','bytes',0,'modifiedDatenum',0,'sha256',''),numel(files),1);
for k=1:numel(files),r(k)=file_record(files{k});end
end
function r=file_record(pathText)
d=dir(pathText);assert(numel(d)==1,'Required file missing: %s',pathText);
r=struct('path',pathText,'bytes',d.bytes,'modifiedDatenum',d.datenum, ...
    'sha256',file_sha256(pathText));
end
function assert_expected(records,expected)
for k=1:numel(records),assert(strcmp(records(k).sha256,expected{k}), ...
        'Frozen hash mismatch: %s',records(k).path);end
end
function ok=records_match(records,expected)
ok=numel(records)==numel(expected);
for k=1:numel(records),ok=ok&&strcmp(records(k).sha256,expected{k});end
end
function ok=records_equal(a,b)
ok=numel(a)==numel(b);
for k=1:numel(a),ok=ok&&record_equal(a(k),b(k));end
end
function ok=record_equal(a,b)
ok=a.bytes==b.bytes&&a.modifiedDatenum==b.modifiedDatenum&& ...
    strcmp(a.sha256,b.sha256);
end
function hash=file_sha256(pathText)
d=java.security.MessageDigest.getInstance('SHA-256');
s=java.io.FileInputStream(java.io.File(pathText));
ds=java.security.DigestInputStream(s,d);c=onCleanup(@()ds.close());
while ds.read()~=-1,end
b=typecast(d.digest(),'uint8');hash=lower(reshape(dec2hex(b,2).',1,[]));clear c
end
