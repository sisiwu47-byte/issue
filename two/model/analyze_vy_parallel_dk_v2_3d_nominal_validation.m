        mineig(k)=min(eig((P(:,:,k)+P(:,:,k).')/2));end
s=struct('maxAsymmetry',max(asym),'minimumEigenvalue',min(mineig));
s.valid=s.maxAsymmetry<=1e-12&&s.minimumEigenvalue>=-1e-12;
end
function [hits,audit]=input_rows_at_hits(data,inputTime,hitTime,w)
inputTime=double(inputTime(:));a=sample_rows(data,numel(inputTime),w);hits=zeros(numel(hitTime),w);
match=zeros(numel(hitTime),1);nearest=zeros(numel(hitTime),1);ambiguous=false;
for k=1:numel(hitTime),delta=abs(inputTime-hitTime(k));nearest(k)=min(delta);ix=find(delta==nearest(k));
    match(k)=numel(ix);tol=32*eps(max(1,abs(hitTime(k))));if nearest(k)>tol,continue;end
    c=a(ix,:);if size(c,1)>1&&any(max(abs(c-c(end,:)),[],2)>1e-12),ambiguous=true;end
    hits(k,:)=c(end,:);end
audit=struct('rawInputSampleCount',numel(inputTime),'hitSampleCount',numel(hitTime), ...
    'matchCountPerHit',match,'nearestTimeDelta',nearest, ...
    'allHitsResolved',all(match>=1)&&all(nearest==0),'duplicateMatchCount',nnz(match>1), ...
    'ambiguousDuplicate',ambiguous,'timestampShiftApplied',false);
end
