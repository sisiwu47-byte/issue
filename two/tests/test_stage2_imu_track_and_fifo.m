% ========================================================================

function test_trapezoidal_integration(testCase)
% TEST 3:
% Explicitly distinguish trapezoidal integration from Euler integration.
%
% The last two non-zero acceleration transitions are:
%
%   0 -> 1
%   1 -> 3
%
% Trapezoidal contribution:
%
%   0.5*Ts*(0+1) + 0.5*Ts*(1+3)

p = estimator_default_params();

N = p.Nwindow;
Ts = p.Ts_est;
tol = 1e-10;

vxZero = ones(4,1);
validGeom = true(4,1);


%% First N samples

%% Explicit reset call
% Reset only clears persistent FIFO/state.
% It is NOT counted as the first valid window sample.

window_delta_velocity_indicator( ...
    0, ...
    0, ...
    0, ...
    zeros(4,1), ...
    validGeom, ...
    1, ...
    p);


%% First N VALID samples

for k = 1:N

    vxWheel = ...
        vxZero * ...
        (k - 1) * Ts;

    ax = 0;

    % At the Nth valid sample:
    % acceleration changes 0 -> 1.
    if k == N
        ax = 1;
    end

    window_delta_velocity_indicator( ...
        ax, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        0, ...          % IMPORTANT: reset already done above
        p);

end


%% N+1 sample: acceleration jumps from 1 to 3

vxWheel = ...
    vxZero * ...
    N * Ts;

[eTrap, dVWheelTrap, dVImuTrap, ...
    windowReadyTrap, slipReadyTrap, residualValidTrap] = ...
    window_delta_velocity_indicator( ...
        3, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        0, ...
        p);


%% Expected integration values

dvImuTrapExpected = ...
    0.5 * Ts * (0 + 1) + ...
    0.5 * Ts * (1 + 3);

dvImuEulerCurrentExpected = ...
    Ts * (1 + 3);

dvImuEulerPreviousExpected = ...
    Ts * 1;


%% Status checks

testCase.verifyTrue( ...
    windowReadyTrap, ...
    'TEST3: window should be ready.');

testCase.verifyTrue( ...
    slipReadyTrap, ...
    'TEST3: slip calculation should be ready.');

testCase.verifyTrue( ...
    all(residualValidTrap), ...
    'TEST3: all residuals should be valid.');


%% Finite outputs

testCase.verifyTrue( ...
    all(isfinite(eTrap)), ...
    'TEST3: eSlip should be finite.');

testCase.verifyTrue( ...
    all(isfinite(dVWheelTrap)), ...
    'TEST3: DeltaVWheel should be finite.');


%% Must equal trapezoidal result

testCase.verifyEqual( ...
    dVImuTrap, ...
    dvImuTrapExpected, ...
    'AbsTol', tol, ...
    'TEST3: IMU integration should use trapezoidal integration.');


%% Must NOT equal current-sample Euler integration

testCase.verifyGreaterThan( ...
    abs(dVImuTrap - dvImuEulerCurrentExpected), ...
    5e-3, ...
    'TEST3: result unexpectedly matches current-sample Euler integration.');


%% Must NOT equal previous-sample Euler integration

testCase.verifyGreaterThan( ...
    abs(dVImuTrap - dvImuEulerPreviousExpected), ...
    1e-3, ...
    'TEST3: result unexpectedly matches previous-sample Euler integration.');

end


%% ========================================================================
% TEST 4
% ========================================================================

function test_window_boundary_N_and_Nplus1(testCase)
% TEST 4:
%
% Formal Stage-2 boundary:
%
%   Calls 1 ... N-1:
%       windowReady  = false
%       slipReady    = false
%
%   Call N:
%       windowReady  = true
%       slipReady    = true
%       residualValid = false
%
%   Call N+1:
%       formal DeltaV/eSlip become valid

p = estimator_default_params();

N = p.Nwindow;
Ts = p.Ts_est;
tol = 1e-10;

vxZero = ones(4,1);
validGeom = true(4,1);


%% Calls 1 ... N
%% Explicit reset call
% Reset clears persistent FIFO state and is NOT counted
% as the first valid window sample.

window_delta_velocity_indicator( ...
    1, ...
    0, ...
    0, ...
    zeros(4,1), ...
    validGeom, ...
    1, ...
    p);
for k = 1:N

    vxWheel = ...
        vxZero * ...
        (k - 1) * Ts;

    [eStartup, dVWheelStartup, dVImuStartup, ...
        windowReadyStartup, slipReadyStartup, ...
        residualValidStartup] = ...
        window_delta_velocity_indicator( ...
            1, ...
            0, ...
            0, ...
            vxWheel, ...
            validGeom, ...
            0, ...
            p);


    if k < N

        testCase.verifyFalse( ...
            windowReadyStartup, ...
            ['TEST4: windowReady should be false at call ', ...
             num2str(k)]);

        testCase.verifyFalse( ...
            slipReadyStartup, ...
            ['TEST4: slipReady should be false at call ', ...
             num2str(k)]);

        testCase.verifyFalse( ...
            any(residualValidStartup), ...
            'TEST4: residuals must be invalid during startup.');

        testCase.verifyTrue( ...
            isnan(dVImuStartup), ...
            'TEST4: DeltaVImu should be NaN during startup.');

        testCase.verifyTrue( ...
            all(isnan(dVWheelStartup)), ...
            'TEST4: DeltaVWheel should be NaN during startup.');

    else

        %% Nth call

        testCase.verifyTrue( ...
            windowReadyStartup, ...
            'TEST4: windowReady should become true at call N.');

        testCase.verifyTrue( ...
            slipReadyStartup, ...
            'TEST4: slipReady should become true at call N.');

        testCase.verifyFalse( ...
            any(residualValidStartup), ...
            'TEST4: formal residual should not yet be valid at call N.');

        testCase.verifyTrue( ...
            isnan(dVImuStartup), ...
            'TEST4: DeltaVImu should still be NaN at call N.');

        testCase.verifyTrue( ...
            all(isnan(dVWheelStartup)), ...
            'TEST4: DeltaVWheel should still be NaN at call N.');

        testCase.verifyTrue( ...
            all(isnan(eStartup)), ...
            'TEST4: eSlip should still be NaN at call N.');

    end

end


%% N+1 call

vxWheel = ...
    vxZero * ...
    N * Ts;

[eStartup, dVWheelStartup, dVImuStartup, ...
    windowReadyStartup, slipReadyStartup, ...
    residualValidStartup] = ...
    window_delta_velocity_indicator( ...
        1, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        0, ...
        p);


%% Formal residual now valid

testCase.verifyTrue(windowReadyStartup);

testCase.verifyTrue(slipReadyStartup);

testCase.verifyTrue(all(residualValidStartup));

testCase.verifyTrue(isfinite(dVImuStartup));

testCase.verifyTrue(all(isfinite(dVWheelStartup)));

testCase.verifyTrue(all(isfinite(eStartup)));


%% 0.5-s accumulated increment

expectedDeltaV = N * Ts;

testCase.verifyEqual( ...
    dVImuStartup, ...
    expectedDeltaV, ...
    'AbsTol', tol);

testCase.verifyEqual( ...
    dVWheelStartup, ...
    expectedDeltaV * ones(4,1), ...
    'AbsTol', tol);

end


