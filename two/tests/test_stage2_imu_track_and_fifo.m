%% ========================================================================
% TEST 6
% ========================================================================

function test_reset_during_operation(testCase)
% TEST 6:
% A reset during mature operation must clear FIFO/window state.
%
% This version intentionally follows the same N/N+1 semantics as TEST 4.

p = estimator_default_params();

N = p.Nwindow;

vxWheel = ones(4,1) * 10;
validGeom = true(4,1);


%% ------------------------------------------------------------------------
% First mature the estimator
% -------------------------------------------------------------------------

for k = 1:(N + 1)

    [~, ~, ~, windowReady] = ...
        window_delta_velocity_indicator( ...
            0.5, ...
            0, ...
            0, ...
            vxWheel, ...
            validGeom, ...
            (k == 1), ...
            p);

end

testCase.verifyTrue( ...
    windowReady, ...
    'TEST6: pre-reset window should already be mature.');


%% ------------------------------------------------------------------------
% Force reset in the middle of operation
% -------------------------------------------------------------------------

[eReset, dVWheelReset, dVImuReset, ...
    windowReadyReset, slipReadyReset, residualValidReset] = ...
    window_delta_velocity_indicator( ...
        0.5, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        1, ...
        p);


%% Immediately after reset, window must no longer be mature

testCase.verifyFalse( ...
    windowReadyReset, ...
    'TEST6: reset must clear windowReady.');

testCase.verifyFalse( ...
    slipReadyReset, ...
    'TEST6: reset must clear slipReady.');

testCase.verifyFalse( ...
    any(residualValidReset), ...
    'TEST6: reset must invalidate formal residuals.');

testCase.verifyTrue( ...
    isnan(dVImuReset), ...
    'TEST6: DeltaVImu should be unavailable immediately after reset.');

testCase.verifyTrue( ...
    all(isnan(dVWheelReset)), ...
    'TEST6: DeltaVWheel should be unavailable immediately after reset.');

testCase.verifyTrue( ...
    all(isnan(eReset)), ...
    'TEST6: eSlip should be unavailable immediately after reset.');


%% ------------------------------------------------------------------------
% The reset sample is sample 1 of the new FIFO.
% Add samples 2 ... N+1.
% -------------------------------------------------------------------------

for k = 2:(N + 1)

    [eSlip, dVWheel, dVImu, ...
        windowReady, slipReady, residualValid] = ...
        window_delta_velocity_indicator( ...
            0.5, ...
            0, ...
            0, ...
            vxWheel, ...
            validGeom, ...
            0, ...
            p);

end


%% Nth post-reset sample: window ready, formal residual not yet available

testCase.verifyTrue( ...
    windowReady, ...
    'TEST6: window should mature again at post-reset call N.');

testCase.verifyTrue( ...
    slipReady, ...
    'TEST6: slipReady should mature again.');

testCase.verifyFalse( ...
    any(residualValid), ...
    'TEST6: residual should still be invalid at call N.');

testCase.verifyTrue( ...
    isnan(dVImu), ...
    'TEST6: DeltaVImu should still be NaN at call N.');

testCase.verifyTrue( ...
    all(isnan(dVWheel)), ...
    'TEST6: DeltaVWheel should still be NaN at call N.');

testCase.verifyTrue( ...
    all(isnan(eSlip)), ...
    'TEST6: eSlip should still be NaN at call N.');


%% ------------------------------------------------------------------------
% N+1 post-reset sample
% -------------------------------------------------------------------------

[eSlip, dVWheel, dVImu, ...
    windowReady, slipReady, residualValid] = ...
    window_delta_velocity_indicator( ...
        0.5, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        0, ...
        p);


%% Formal calculation restored

testCase.verifyTrue(windowReady);

testCase.verifyTrue(slipReady);

testCase.verifyTrue(all(residualValid));

testCase.verifyTrue(all(isfinite(dVWheel)));

testCase.verifyTrue(isfinite(dVImu));

testCase.verifyTrue(all(isfinite(eSlip)));

end


%% ========================================================================
% TEST 7
% ========================================================================

function test_imu_nan_invalidates_imu_life(testCase)
% TEST 7:
% NaN Ax must invalidate the IMU track.
%
% It must NOT generate a fake finite DeltaVImu residual.

p = estimator_default_params();

N = p.Nwindow;

vxWheel = ones(4,1);
validGeom = true(4,1);


%% First sample / reset

[~, ~, ~, ~, ~, ~, imuLife] = ...
    window_delta_velocity_indicator( ...
        1, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        1, ...
        p);

testCase.verifyFalse( ...
    imuLife, ...
    'TEST7: reset call should clear IMU life state.');


%% Continue with healthy IMU samples (N+1 non-reset samples)

for k = 2:(N + 2)

    [~, ~, ~, ~, ~, ~, imuLife] = ...
        window_delta_velocity_indicator( ...
            1, ...
            0, ...
            0, ...
            vxWheel, ...
            validGeom, ...
            0, ...
            p);

    testCase.verifyTrue( ...
        imuLife, ...
        ['TEST7: imuLife unexpectedly false at healthy call ', ...
         num2str(k)]);

end


%% Inject Ax = NaN

[eNaN, dVWheelNaN, dVImuNaN, ...
    windowReadyNaN, slipReadyNaN, ...
    residualValidNaN, imuLifeNaN] = ...
    window_delta_velocity_indicator( ...
        NaN, ...
        0, ...
        0, ...
        vxWheel, ...
        validGeom, ...
        0, ...
        p);


%% IMU track must become invalid

testCase.verifyFalse( ...
    imuLifeNaN, ...
    'TEST7: Ax=NaN must set imuLife=false.');


%% No fake IMU residual

testCase.verifyTrue( ...
    isnan(dVImuNaN), ...
    'TEST7: DeltaVImu must be NaN when IMU data are invalid.');


%% Formal residual cannot be trusted with invalid IMU track

testCase.verifyTrue( ...
    all(isnan(eNaN)) || ...
    all(~residualValidNaN), ...
    ['TEST7: invalid IMU must not produce ', ...
     'fake valid eSlip residuals.']);


%% Wheel path itself should not be contaminated by Ax NaN

testCase.verifyTrue( ...
    all(isfinite(dVWheelNaN)) || ...
    all(isnan(dVWheelNaN)), ...
    ['TEST7: wheel-side output should have ', ...
     'consistent finite/NaN semantics.']);


%% Keep explicit scalar status checks

testCase.verifyTrue(isscalar(windowReadyNaN));

testCase.verifyTrue(isscalar(slipReadyNaN));

end


